// Generates src/gen/el.ts from tools/bindgen/surface.txt: every `El` builder method the renderer
// can call from an attribute (with the kinds of its parameters, to coerce static strings) and
// every `on_*` handler it can wire to a Svelte event. `bun scripts/gen-el.ts --check` fails when
// the committed file is stale, as `bun run check:bindings` does for runex's own generated code.
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const SURFACE = fileURLToPath(new URL("../../../tools/bindgen/surface.txt", import.meta.url))
const OUT = fileURLToPath(new URL("../src/gen/el.ts", import.meta.url))

/** Builders the renderer handles itself, or that make no sense as an attribute. */
const SKIP = new Set(["child", "children", "clone", "key"])

/** Splits `a: X, b: Y<Z, W>` at top-level commas. */
function params(list: string): { name: string; type: string }[] {
  const out: string[] = []
  let depth = 0
  let cur = ""
  for (const ch of list) {
    if ("([{<".includes(ch)) depth++
    if (")]}>".includes(ch) && !(ch === ">" && cur.endsWith("="))) depth--
    if (ch === "," && depth === 0) {
      out.push(cur.trim())
      cur = ""
    } else cur += ch
  }
  if (cur.trim()) out.push(cur.trim())
  return out.map((p) => {
    const at = p.indexOf(":")
    return { name: p.slice(0, at).trim().replace(/\?$/, ""), type: p.slice(at + 1).trim() }
  })
}

/**
 * One letter per parameter: `n` number, `b` boolean, `s` string (and string enums), `c` Color,
 * `f` a function (wrapped so it runs as a handler), `v` a state handler (`(s) => S | void`: its
 * return is dropped, since a value would replace Rune's state), `x` anything else (passed through).
 * A trailing `?` marks `| null`.
 */
function kind(type: string): string {
  const nullable = type.endsWith(" | null")
  const t = nullable ? type.slice(0, -" | null".length) : type
  let k = "x"
  if (t === "number") k = "n"
  else if (t === "boolean") k = "b"
  else if (t === "string") k = "s"
  else if (t === "Color") k = "c"
  else if (/=> S \| void\)?$/.test(t)) k = "v"
  else if (t.includes("=>")) k = "f"
  else if (/^[A-Z][A-Za-z]*$/.test(t) && ENUMS.has(t)) k = "s"
  return nullable ? k + "?" : k
}

const surface = readFileSync(SURFACE, "utf8").split("\n")
// Unit-only enums arrive as strings, so a static attribute can name a variant (`cursor="Pointer"`).
const ENUMS = new Set(surface.filter((l) => l.startsWith("enum ")).map((l) => l.slice(5).trim()))

const methods: [string, string[]][] = []
const events: [string, { state: boolean; args: string[]; returns: string }][] = []
for (const line of surface) {
  const m = /^method El\.([a-z_0-9]+)(<[^>]*>)?\((.*)\): (.+)$/.exec(line)
  if (!m) continue
  const [, name, , list, ret] = m
  const ps = params(list!)
  if (name!.startsWith("on_")) {
    const f = ps[0]!.type
    const inner = /^\((.*)\) => (.+)$/.exec(f)
    if (!inner) continue
    const args = params(inner[1]!)
    const state = args[0]?.type === "S"
    events.push([name!, { state, args: args.slice(state ? 1 : 0).map((a) => a.name), returns: inner[2]! }])
    continue
  }
  if (ret !== "this" || SKIP.has(name!)) continue
  methods.push([name!, ps.map((p) => kind(p.type))])
}

const body = `// Generated by scripts/gen-el.ts from tools/bindgen/surface.txt. Do not edit.

/**
 * El's builder methods by name, with one kind letter per parameter: \`n\` number, \`b\` boolean,
 * \`s\` string or unit enum, \`c\` Color, \`f\` function, \`v\` state handler (return dropped),
 * \`x\` anything else; \`?\` adds \`null\`.
 */
export const EL_METHODS: Record<string, readonly string[]> = {
${methods.map(([n, k]) => `  ${n}: ${JSON.stringify(k)},`).join("\n")}
}

/** El's \`on_*\` handlers: whether the callback takes the state first, its other parameters, what it returns. */
export const EL_EVENTS: Record<string, { state: boolean; args: readonly string[]; returns: string }> = {
${events.map(([n, e]) => `  ${n}: ${JSON.stringify(e)},`).join("\n")}
}

export type ElMethodName =
${methods.map(([n]) => `  | ${JSON.stringify(n)}`).join("\n")}

export type ElEventName =
${events.map(([n]) => `  | ${JSON.stringify(n)}`).join("\n")}
`

if (process.argv.includes("--check")) {
  let current = ""
  try {
    current = readFileSync(OUT, "utf8")
  } catch {}
  if (current !== body) {
    console.error("src/gen/el.ts is stale: run `bun run gen` in packages/svelte")
    process.exit(1)
  }
  console.log(`src/gen/el.ts is current (${methods.length} methods, ${events.length} events)`)
} else {
  writeFileSync(OUT, body)
  console.log(`wrote src/gen/el.ts: ${methods.length} methods, ${events.length} events`)
}
